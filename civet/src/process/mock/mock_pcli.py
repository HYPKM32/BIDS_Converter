def create_fake_file(filepath, file_type="text"):
    """
    가짜 파일 생성
    
    Args:
        filepath (str): 생성할 파일 경로
        file_type (str): 파일 타입 ("text", "binary", "mnc", "obj", "xfm", "dat", "png")
    """
    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    
    if file_type == "text" or filepath.endswith(('.txt', '.log', '.finished', '.dat')):
        # 텍스트 파일
        with open(filepath, 'w') as f:
            f.write(f"Mock CIVET output file: {os.path.basename(filepath)}\n")
            f.write("This is a test file generated by mock_pcli.py\n")
    
    elif file_type == "binary" or filepath.endswith(('.mnc', '.obj', '.xfm', '.sm', '.png')):
        # 바이너리 파일 (빈 파일)
        with open(filepath, 'wb') as f:
            # 최소한의 데이터 (1KB)
            f.write(b'\x00' * 1024)
    
    else:
        # 기타 파일
        with open(filepath, 'w') as f:
            f.write(f"Mock file: {os.path.basename(filepath)}\n")


def create_civet_output_structure(tmp_dir, working_name):
    """
    CIVET 출력 디렉토리 구조 생성
    
    Args:
        tmp_dir (str): 임시 디렉토리 경로
        working_name (str): working_name (예: sub-XXX_run-01_exe-01_drv-civet)
    
    Returns:
        str: CIVET 출력 디렉토리 경로 (tmp_dir/working_name)
    """
    civet_output_dir = os.path.join(tmp_dir, working_name)
    
    logger.info(f"Creating fake CIVET output structure: {civet_output_dir}")
    
    # 각 폴더별로 파일 생성
    for folder, files in CIVET_OUTPUT_STRUCTURE.items():
        folder_path = os.path.join(civet_output_dir, folder)
        os.makedirs(folder_path, exist_ok=True)
        
        for filename in files:
            # 파일명에 working_name 추가
            full_filename = f"{working_name}_{filename}"
            
            # logs 폴더는 확장자 형식이 다름
            if folder == "logs":
                if '.' in filename:
                    # xxx.log, xxx.finished 형식
                    full_filename = f"{working_name}.{filename}"
                else:
                    # options 같은 확장자 없는 파일
                    full_filename = f"{working_name}.{filename}"
            
            filepath = os.path.join(folder_path, full_filename)
            create_fake_file(filepath)
    
    logger.info(f"Created fake CIVET output with {sum(len(f) for f in CIVET_OUTPUT_STRUCTURE.values())} files")
    
    return civet_output_dir


def collect_directory_structure(directory_path, base_name):
    """
    디렉토리의 전체 구조를 '폴더/하위폴더/파일명' 형식으로 수집
    (pcli.py와 동일)
    """
    items = []
    
    for root, dirs, files in os.walk(directory_path):
        rel_root = os.path.relpath(root, directory_path)
        
        if rel_root == '.':
            prefix = base_name
        else:
            prefix = os.path.join(base_name, rel_root)
        
        for file in files:
            file_path = os.path.join(prefix, file)
            items.append(file_path)
    
    return items


def run_single_mock_command(command_list, index, derived_data, civet_work_mapping, delay=2):
    """
    단일 CIVET 커맨드 실행 시뮬레이션 (가짜 파일 생성)
    
    Args:
        command_list (list): 실행할 커맨드 토큰 리스트
        index (int): 커맨드 인덱스
        derived_data (dict): 해당 커맨드의 derived_data
        civet_work_mapping (dict): 작업 디렉토리 매핑 정보
        delay (int): 실행 지연 시간 (초) - CIVET 실행 시간 시뮬레이션
    
    Returns:
        dict: 실행 결과 (pcli.run_single_command와 동일 구조)
    """
    output_path = derived_data.get('output_path', '')
    mapping = civet_work_mapping.get(output_path, {})
    tmp_dir = mapping.get('tmp_dir', '')
    working_name = mapping.get('working_name', '')
    
    result = {
        "index": index,
        "command": ' '.join(command_list),
        "success": False,
        "tmp_dir": tmp_dir,
        "working_name": working_name,
        "output_path": output_path,
        "moved": False,
        "tmp_cleaned": False,
        "exit_code": None,
        "stdout": "",
        "stderr": "",
        "error": None,
        "moved_items": [],
        "derived_data": derived_data
    }
    
    try:
        logger.info(f"[MOCK {index}] Simulating CIVET execution: {' '.join(command_list[:3])}...")
        
        # CIVET 실행 시간 시뮬레이션
        time.sleep(delay)
        
        # 성공 시뮬레이션
        result["exit_code"] = 0
        result["stdout"] = f"Mock CIVET execution completed for {working_name}"
        
        logger.info(f"[MOCK {index}] Creating fake CIVET output structure...")
        
        # 가짜 CIVET 출력 구조 생성
        civet_output_dir = create_civet_output_structure(tmp_dir, working_name)
        
        if not os.path.exists(civet_output_dir):
            result["error"] = f"Failed to create fake CIVET output: {civet_output_dir}"
            logger.error(f"[MOCK {index}] {result['error']}")
            return result
        
        logger.info(f"[MOCK {index}] Fake CIVET output created: {civet_output_dir}")
        
        # output_path 디렉토리 생성
        os.makedirs(output_path, exist_ok=True)
        
        # working_name 하위 내용물만 output_path로 복사
        logger.info(f"[MOCK {index}] Moving files from {civet_output_dir} to {output_path}")
        
        moved_items = []
        
        import shutil
        
        for item in os.listdir(civet_output_dir):
            source_item = os.path.join(civet_output_dir, item)
            dest_item = os.path.join(output_path, item)
            
            try:
                if os.path.isdir(source_item):
                    # 디렉토리인 경우: 전체 트리 구조 수집
                    shutil.copytree(source_item, dest_item, dirs_exist_ok=True)
                    
                    # 디렉토리 하위의 모든 파일 목록 수집
                    dir_structure = collect_directory_structure(source_item, item)
                    moved_items.extend(dir_structure)
                    
                    logger.debug(f"[MOCK {index}]   Moved directory: {item} ({len(dir_structure)} items)")
                else:
                    # 파일인 경우: 직접 복사
                    shutil.copy2(source_item, dest_item)
                    moved_items.append(item)
                    logger.debug(f"[MOCK {index}]   Moved file: {item}")
                
            except Exception as e:
                logger.warning(f"[MOCK {index}]   Failed to move {item}: {e}")
        
        result["moved"] = True
        result["moved_items"] = moved_items
        logger.info(f"[MOCK {index}] Moved {len(moved_items)} items to {output_path}")
        
        # tmp 디렉토리 삭제
        try:
            shutil.rmtree(tmp_dir)
            result["tmp_cleaned"] = True
            logger.info(f"[MOCK {index}] Cleaned tmp directory: {tmp_dir}")
        except Exception as e:
            logger.warning(f"[MOCK {index}] Failed to clean tmp directory {tmp_dir}: {e}")
        
        result["success"] = True
        return result
        
    except Exception as e:
        result["error"] = str(e)
        logger.error(f"[MOCK {index}] Unexpected error: {e}", exc_info=True)
        return result


def execute_commands(command_list, derived_data_list, civet_work_mapping, workers, delay=2):
    """
    CIVET 커맨드들을 병렬로 시뮬레이션 (가짜 파일 생성)
    
    Args:
        command_list (list): 실행할 커맨드 리스트
        derived_data_list (list): 각 커맨드의 derived_data
        civet_work_mapping (dict): {output_path: {"tmp_dir": ..., "working_name": ...}}
        workers (int): 최대 동시 실행 노드 수
        delay (int): 각 작업의 지연 시간 (초) - 기본 2초
    
    Returns:
        list: execution_results (pcli.execute_commands와 동일 구조)
        
    Raises:
        RuntimeError: 하나라도 실패한 경우
        ValueError: 입력 리스트 길이 불일치
    """
    logger.warning("=" * 80)
    logger.warning("USING MOCK PCLI - NO REAL CIVET EXECUTION")
    logger.warning("Generating fake files for testing purposes")
    logger.warning("=" * 80)
    
    # 입력 검증
    if len(command_list) != len(derived_data_list):
        raise ValueError(
            f"command_list and derived_data_list length mismatch: "
            f"{len(command_list)} vs {len(derived_data_list)}"
        )
    
    total_commands = len(command_list)
    logger.info(f"Starting mock parallel execution of {total_commands} commands with {workers} workers")
    logger.info(f"Each command will take approximately {delay} seconds")
    
    execution_results = [None] * total_commands
    
    # 병렬 실행 (ThreadPoolExecutor로 충분 - I/O 위주)
    with ThreadPoolExecutor(max_workers=workers) as executor:
        future_to_index = {}
        
        for idx, (cmd, derived_data) in enumerate(zip(command_list, derived_data_list)):
            future = executor.submit(
                run_single_mock_command,
                cmd,
                idx,
                derived_data,
                civet_work_mapping,
                delay
            )
            future_to_index[future] = idx
        
        logger.info(f"Submitted {len(future_to_index)} mock commands to executor")
        
        completed = 0
        for future in as_completed(future_to_index):
            idx = future_to_index[future]
            
            try:
                result = future.result()
                execution_results[idx] = result
                completed += 1
                
                if result["success"]:
                    logger.info(
                        f"[MOCK {idx}] Completed successfully "
                        f"({completed}/{total_commands})"
                    )
                else:
                    logger.error(
                        f"[MOCK {idx}] Failed: {result['error']} "
                        f"({completed}/{total_commands})"
                    )
                    
            except Exception as e:
                logger.error(f"[MOCK {idx}] Exception during execution: {e}", exc_info=True)
                execution_results[idx] = {
                    "index": idx,
                    "command": ' '.join(command_list[idx]) if idx < len(command_list) else "unknown",
                    "success": False,
                    "error": str(e),
                    "exit_code": None,
                    "moved": False,
                    "tmp_cleaned": False,
                    "moved_items": []
                }
                completed += 1
    
    # 결과 요약
    success_count = sum(1 for r in execution_results if r and r["success"])
    failed_count = total_commands - success_count
    
    logger.info(f"Mock execution completed: {success_count} succeeded, {failed_count} failed")
    
    # 실패한 커맨드 상세 로그
    if failed_count > 0:
        logger.error(f"{failed_count}/{total_commands} mock commands failed:")
        
        for result in execution_results:
            if result and not result["success"]:
                logger.error(f"  [MOCK {result['index']}] {result['command']}")
                logger.error(f"    Error: {result['error']}")
        
        raise RuntimeError(
            f"{failed_count} out of {total_commands} mock CIVET commands failed. "
            f"Check logs for details."
        )
    
    logger.info(f"All {total_commands} mock commands completed successfully")
    logger.warning("=" * 80)
    logger.warning("MOCK PCLI EXECUTION FINISHED")
    logger.warning("=" * 80)
    
    return execution_results